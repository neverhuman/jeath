#!/usr/bin/env python3
"""Generate every experimental table from the committed reference JSON."""
import argparse
import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "evidence/reference"
OUT = ROOT / "docs/generated"


def load(name):
    return json.loads((DATA / f"{name}.json").read_text())


def generate():
    model = load("model")
    full = next(r for r in model if r["enforcer"] == "complete")
    omitted = next(r for r in model if not r["budget_in_specification"])
    labels = {"complete": "Complete atomic enforcer", "unconstrained": "No enforcement",
              "reject_all": "Reject everything", "per_action": "Per-action amount limit",
              "per_actor": "Separate per-actor limits", "prepare_only": "Budget at preparation",
              "no_replay": "Omit identifier check", "no_revocation": "Omit revocation check",
              "no_version": "Omit version check", "no_destination": "Omit destination check",
              "reset_restart": "Reset ledger on restart", "reset_renewal": "Reset ledger on renewal"}
    tex = [r"\begin{table*}[t]\centering\small",
           r"\begin{tabularx}{\textwidth}{@{}Lrrrl@{}}\toprule",
           r"Enforcer & States & Checks & Tasks & First violations\\\midrule"]
    for row in model:
        label = labels[row["enforcer"]]
        if not row["budget_in_specification"]:
            label = "Per-action; budget omitted"
        kinds = ", ".join(row["declared_violations"]) or "None declared"
        tex.append(f"{label} & {row['states']:,} & {row['checks']:,} & {row['positive_tasks_passed']}/20 & {kinds}\\\\")
    tex += [r"\bottomrule\end{tabularx}",
            r"\caption{Fresh Rust exploration of all 22 actions at each reachable accepted state. Violating edges are recorded and not expanded. Counts are exhaustive within the model, not failure probabilities. The omitted-budget row accepts up to eight units.}\label{tab:results}\end{table*}"]
    numbers = f"% Generated by scripts/paper.py; do not edit.\n\\newcommand{{\\CheckedStates}}{{{full['states']:,}}}\n\\newcommand{{\\CheckedEdges}}{{{full['checks']:,}}}\n\\newcommand{{\\OmittedStates}}{{{omitted['states']:,}}}\n\\newcommand{{\\OmittedEdges}}{{{omitted['checks']:,}}}\n"
    monitors = load("monitors")
    names = {"neural_shared": "Six neural, shared input", "mixed_shared": "Neural + linear, shared",
             "mixed_independent": "Mixed, independent inputs", "mixed_feedback8": "Mixed, eight feedback queries"}
    mon = [r"\begin{table*}[t]\centering\small\begin{tabularx}{\textwidth}{@{}Lrrrrr@{}}\toprule",
           r"Pipeline & Radius & Single miss & Joint six misses & Product & False block\\\midrule"]
    for row in monitors["summary"]:
        joint, product = row["joint"], row["product"]
        mon.append(f"{names[row['arm']]} & {row['radius']:g} & {100*row['mean_single']['mean']:.2f}\\% & "
                   f"${100*joint['mean']:.3f}\\pm{100*joint['approximate_95_half_width']:.3f}$\\% & "
                   f"{100*product['mean']:.4f}\\% & {100*row['false_block']['mean']:.2f}\\%\\\\")
    mon += [r"\bottomrule\end{tabularx}\caption{New synthetic classifier experiment; uncertainty is 1.96 standard errors across eight independent training-task seeds. The product is computed within each seed before averaging. False blocks are measured on benign episodes and show the cost of stacking gates. They are not measured AI deployment risks.}\label{tab:monitors}\end{table*}"]
    # Empirical depth curves, with all raw counts retained in monitors.json.
    plot = [r"\begin{figure}[t]\centering\begin{tikzpicture}",
            r"\begin{axis}[width=.96\columnwidth,height=5.2cm,xmin=1,xmax=6,ymode=log,ymin=.00001,ymax=1,xtick={1,...,6},xlabel={Number of gates},ylabel={Joint miss rate},legend style={font=\scriptsize,at={(.03,.03)},anchor=south west},grid=major]" ]
    for arm, color in [("neural_shared", "teal"), ("mixed_shared", "violet"), ("mixed_independent", "gold")]:
        selected = [r for r in monitors["tasks"] if r["arm"] == arm and r["radius"] == 0]
        coords = " ".join(f"({j+1},{sum(r['joint_miss'][j] for r in selected)/len(selected):.12g})" for j in range(6))
        plot.append(f"\\addplot[{color},mark=*] coordinates {{{coords}}};\\addlegendentry{{{names[arm]}}}")
    plot += [r"\end{axis}\end{tikzpicture}\caption{Measured held-out joint misses at increasing depth, before edits. Shared evidence creates dependence even across the two classifier families. Independently sampled inputs impose a different experiment.}\label{fig:monitors}\end{figure}"]
    runtime = load("runtime")
    rt = [r"\begin{table}[t]\centering\small\begin{tabular}{rrrr}\toprule",
          r"Processes & Commits & Commits/s & p95 (ms)\\\midrule"]
    for row in runtime["throughput"]:
        rt.append(f"{row['workers']} & {row['executed']} & {row['transactions_per_second']:.1f} & {row['p95_us']/1000:.2f}\\\\")
    rt += [r"\bottomrule\end{tabular}\caption{Single runs on the recorded host with SQLite WAL and synchronous FULL. Setup and grants precede timing; process scheduling and lock waiting remain included. Shared-host contention and storage affect these descriptive measurements.}\label{tab:runtime}\end{table}"]
    cov = load("coverage")["paired_worlds"]
    covtext = (f"The paired reporting fixture produces {cov['reports']:,} reports from {cov['visible_classes']} visible classes. "
               f"Its Good--Turing reported coverage is {100*cov['good_turing_reported_coverage']:.2f}\\%, "
               f"while observed-class mass is {100*cov['honest_true_mass']:.2f}\\% in the complete world and "
               f"{100*cov['identical_reports_hidden_15_percent_mass']:.2f}\\% when an unreported family carries 15\\% "
               "of target mass. The report stream is identical by construction. This demonstrates non-identifiability "
               "from reports alone, not the prevalence of withholding in practice.\n")
    sel = load("selection")
    selection = [r"\begin{table}[t]\centering\small\begin{tabular}{lrr}\toprule",
                 r"Selection rule & Gamble share & Welfare\\\midrule"]
    for row in sel["gamble"]:
        name = row["score"].replace("_", " ")
        selection.append(f"{name} & {100*row['gamble_share']['mean']:.2f}\\% & {row['final_welfare']['mean']:.3f}\\\\")
    selection += [r"\bottomrule\end{tabular}\caption{Eight populations of 400 agents over 60 generations. The gamble has lower expected private return and imposes an additional stipulated welfare loss. These model assumptions drive the interpretation; no trained assistant or human delegation is measured.}\label{tab:selection}\end{table}"]
    result = {"numbers.tex": numbers, "model-table.tex": "\n".join(tex)+"\n",
            "monitor-table.tex": "\n".join(mon)+"\n", "monitor-figure.tex": "\n".join(plot)+"\n",
            "runtime-table.tex": "\n".join(rt)+"\n", "coverage.tex": covtext,
            "selection-table.tex": "\n".join(selection)+"\n"}
    result.update(generate_v2())
    return result


def generate_v2():
    data = ROOT / "evidence/v2/reference"
    read = lambda name: json.loads((data/f"{name}.json").read_text())
    proof = int(re.search(r"verification results:: (\d+) verified, 0 errors",read("proof")["output"]).group(1))
    ablations = read("ablations")
    faults = [r for r in read("faults") if "trace" in r]
    races = read("races")
    controls = read("controllers")["rows"]
    cost = read("revocation-cost")
    benchmark = read("benchmark-controls")
    macros = f"% Generated from validated v2 evidence; do not edit.\n\\newcommand{{\\VTwoProofs}}{{{proof}}}\n\\newcommand{{\\VTwoTraces}}{{{ablations['searched_traces']}}}\n"
    table = [r"\begin{table}[t]\centering\small\begin{tabularx}{\columnwidth}{@{}Lr@{}}\toprule",
             r"Recorded check & Result\\\midrule",
             f"Application core obligations & {proof} verified\\\\",
             f"Sequential fault histories & {len(faults)} passed\\\\",
             f"Concurrent race repetitions & {len(races)} passed\\\\",
             f"Abstract omission sets with witnesses & {sum(bool(r['shortest_searched_witness']) for r in ablations['rows'])}/{len(ablations['rows'])}\\\\",
             f"Native benchmark utility positives & {sum(r.get('native_utility_positive',False) for r in benchmark['rows'])}/{len(benchmark['rows'])}\\\\",
             r"Model campaigns & Unrun\\",
             r"\bottomrule\end{tabularx}\caption{Evidence types remain distinct. Abstract mutation witnesses and native scripted controls are not adversarial model measurements.}\label{tab:v2summary}\end{table}"]
    table += [r"\begin{table}[t]\centering\small\begin{tabularx}{\columnwidth}{@{}Lrr@{}}\toprule",
              r"CPU controller & Safe/useful & Runs\\\midrule"]
    names = {"none":"No enforcement","stateless":"Stateless per-call", "durable_without_fence":"Durable, no fence", "complete":"Complete"}
    for name,label in names.items():
        selected = [r for r in controls if r["controller"]==name]
        table.append(f"{label} & {sum(r['safe_useful'] for r in selected)}/{len(selected)} & {len(selected)}\\\\")
    table += [r"Learned, same checkpoint & Unrun & 0\\",
              r"\bottomrule\end{tabularx}\caption{Sequential scripted shared-budget controls over all six actor populations, with equal permissions. These descriptive outcomes do not support model noninferiority.}\label{tab:v2controllers}\end{table}"]
    table.append(f"The delayed-completion control measured a fence acknowledgment delay of {cost['fence_ack_ms']:.2f} ms with {cost['unavailable_charge_at_ack']} units unavailable at acknowledgment. The injected in-transaction delay was {cost['injected_service_delay_ms']} ms.\n")
    plot = [r"\begin{figure}[t]\centering\begin{tikzpicture}",
            r"\begin{axis}[width=.96\columnwidth,height=4.7cm,xmode=log,log basis x=2,xtick={1,2,4,8,16,32},xticklabels={1,2,4,8,16,32},xlabel={Concurrent actors},ylabel={Observed p95 latency (ms)},grid=major]" ]
    coordinates = []
    for actors in (1,2,4,8,16,32):
        values = sorted(x["latency_ms"] for row in races if row["actors"]==actors for x in row["outcomes"])
        coordinates.append(f"({actors},{values[math.ceil(.95*len(values))-1]:.6g})")
    plot.append(r"\addplot[teal,mark=*] coordinates {"+" ".join(coordinates)+"};")
    host = read("manifest")["hostname"].replace("_",r"\_")
    plot += [r"\end{axis}\end{tikzpicture}",
             f"\\caption{{Durable shared-budget races on {host}; empirical p95 across recorded attempts at each population. Rejected requests and contention are included. Setup is excluded; these are descriptive host measurements.}}\\label{{fig:v2latency}}\\end{{figure}}"]
    return {"v2-numbers.tex":macros,"v2-summary.tex":"\n".join(table)+"\n","v2-races.tex":"\n".join(plot)+"\n"}


if __name__ == "__main__":
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    OUT.mkdir(exist_ok=True)
    for name, content in generate().items():
        path = OUT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale generated file: {path}; run python3 scripts/paper.py")
        else:
            path.write_text(content)
    print("paper tables match reference evidence" if args.check else "generated paper tables")
