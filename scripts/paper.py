MACRO_NAME_RE = re.compile(r"^[A-Za-z]+$")


def load_v1(name):
    return json.loads((DATA_V1 / f"{name}.json").read_text())


def load_v2(name):
    return json.loads((DATA_V2 / f"{name}.json").read_text())


def load_v3(name):
    return json.loads((DATA_V3 / f"{name}.json").read_text())


def format_macros(header_comment, pairs):
    lines = [f"% {header_comment}"]
    seen = set()
    for name, value in pairs:
        assert MACRO_NAME_RE.fullmatch(name), f"Macro name must be strictly alphabetic [A-Za-z]+: {name!r}"
        assert name not in seen, f"Duplicate macro name: {name}"
        seen.add(name)
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")
    return "\n".join(lines) + "\n"


def assert_pure_float(filename, content):
    lines = [ln.strip() for ln in content.strip().splitlines() if ln.strip() and not ln.strip().startswith("%")]
    assert lines, f"empty float file: {filename}"
    assert lines[0].startswith((r"\begin{table", r"\begin{figure")), f"non-float prefix in {filename}: {lines[0]}"
    assert lines[-1].endswith((r"\end{table}", r"\end{table*}", r"\end{figure}", r"\end{figure*}")), (
        f"non-float suffix in {filename}: {lines[-1]}"
    )


